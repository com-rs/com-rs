#!/usr/bin/env python3
"""Generate ``python/comrs/_comrs.pyi``, the type stub of the Rust extension.

The stub is built from the extension itself (``maturin develop`` first): the
signatures come from ``__text_signature__`` (written by PyO3 from the ``signature``
attributes of the bindings), the types from the Google-style docstrings: ``name
(type): …`` in ``Args:``, ``type: …`` in ``Returns:``, and the first words ``type: …``
of the docstring of a property (``(read and write)`` in it makes it writable)::

    python tools/gen_stubs.py           # write python/comrs/_comrs.pyi
    python tools/gen_stubs.py --check   # fail if the stub is out of date (CI)

A function without a ``Returns:`` section returns ``None``; an argument or a property
without a type is ``Any``. The output is formatted by ``ruff format``.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import inspect
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "python" / "comrs" / "_comrs.pyi"

HEADER = '''"""Type stub of the Rust extension ``comrs._comrs``.

Generated by ``tools/gen_stubs.py`` from the built extension (signatures and the
types of the docstrings): do not edit it.
"""

from __future__ import annotations

import os
from collections.abc import Callable
from typing import Any

import numpy as np
from numpy.typing import ArrayLike

from comrs.results import Results

__version__: str

'''

# the special methods kept in the stub, with their signatures
DUNDERS = {
    "__len__": "def __len__(self) -> int: ...",
    "__repr__": "def __repr__(self) -> str: ...",
    "__eq__": "def __eq__(self, other: object) -> bool: ...",
    "__contains__": "def __contains__(self, name: str) -> bool: ...",
    "__getitem__": "def __getitem__(self, name: str) -> Any: ...",
    "__add__": "def __add__(self, other: {cls}) -> {cls}: ...",
    "__or__": "def __or__(self, other: {cls}) -> {cls}: ...",
    "__and__": "def __and__(self, other: {cls}) -> {cls}: ...",
}

TOKENS = {
    "array_like": "ArrayLike",
    "ndarray": "np.ndarray",
    "numpy.ndarray": "np.ndarray",
    "callable": "Callable[..., Any]",
    "os.PathLike": "os.PathLike[str]",
    "dict": "dict[str, Any]",
    "list": "list[Any]",
    "tuple": "tuple[Any, ...]",
}
TYPE_CHARS = re.compile(r"^[\w\.\[\], |]+$")


def extension():
    """The built extension, loaded without the package."""
    found = sorted((ROOT / "python" / "comrs").glob("_comrs*.so")) + sorted(
        (ROOT / "python" / "comrs").glob("_comrs*.pyd")
    )
    if not found:
        raise SystemExit("build the extension first: maturin develop")
    spec = importlib.util.spec_from_file_location("_comrs", found[0])
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def py_type(text: str | None) -> str:
    """A type of a docstring as a type expression of the stub."""
    if not text:
        return "Any"
    text = text.strip()
    if not TYPE_CHARS.match(text):
        return "Any"

    def token(m: re.Match) -> str:
        word = m.group(0)
        return TOKENS.get(word, word)

    # whole words, the bare containers only when not subscripted
    out = re.sub(r"numpy\.ndarray|os\.PathLike|array_like|ndarray|callable", token, text)
    out = re.sub(r"\b(dict|list|tuple)\b(?!\[)", token, out)
    return out


def sections(doc: str | None) -> tuple[dict[str, str], str | None]:
    """The types of the arguments and of the result of a docstring."""
    args: dict[str, str] = {}
    ret = None
    if not doc:
        return args, ret
    lines = doc.splitlines()
    i = 0
    while i < len(lines):
        head = lines[i].strip()
        if head == "Args:":
            i += 1
            while i < len(lines) and (not lines[i].strip() or lines[i].startswith(" ")):
                m = re.match(r"^\s{4}(\*{0,2}\w+) \((.+?)\):", lines[i])
                if m:
                    args[m.group(1)] = m.group(2)
                i += 1
            continue
        if head == "Returns:":
            i += 1
            while i < len(lines) and not lines[i].strip():
                i += 1
            if i < len(lines):
                m = re.match(r"^\s+(.+?):(\s|$)", lines[i])
                if m:
                    ret = m.group(1)
            continue
        i += 1
    return args, ret


def arg_type(text: str | None, default: object) -> str:
    if text is None:
        return "Any"
    optional = text.endswith(", optional")
    t = py_type(text.removesuffix(", optional"))
    if (optional or default is None) and t != "Any" and "None" not in t.split(" | "):
        t += " | None"
    return t


def signature(obj, text_signature: str | None, doc: str | None, *, method: bool) -> str:
    """The parameters and the return type of a callable."""
    args, ret = sections(doc)
    params = ["self"] if method else []
    if text_signature:
        sig = inspect.Signature
        try:
            parsed = inspect.signature(obj)
        except (TypeError, ValueError):
            parsed = None
        if parsed is not None:
            seen_kw = False
            for p in parsed.parameters.values():
                if p.name in ("self", "$self"):
                    continue
                if p.kind is p.KEYWORD_ONLY and not seen_kw:
                    params.append("*")
                    seen_kw = True
                if p.kind is p.VAR_POSITIONAL:
                    params.append(f"*{p.name}: {arg_type(args.get('*' + p.name), sig.empty)}")
                    seen_kw = True
                    continue
                if p.kind is p.VAR_KEYWORD:
                    params.append(f"**{p.name}: {arg_type(args.get('**' + p.name), sig.empty)}")
                    continue
                default = p.default if p.default is not p.empty else sig.empty
                t = arg_type(args.get(p.name), default)
                params.append(f"{p.name}: {t}" + (" = ..." if default is not sig.empty else ""))
    return f"({', '.join(params)}) -> {py_type(ret) if ret else 'None'}"


def prop_type(doc: str | None) -> str:
    if not doc:
        return "Any"
    m = re.match(r"^([\w\.\[\], |]+):\s", doc.strip())
    return py_type(m.group(1)) if m else "Any"


def class_stub(name: str, cls) -> list[str]:
    out = [f"class {name}:"]
    doc = cls.__doc__ or ""
    text = getattr(cls, "__text_signature__", None)
    if text:
        init = signature(cls, text, doc, method=True).rsplit(" -> ", 1)[0]
        out.append(f"    def __init__{init} -> None: ...")
    for attr, member in sorted(vars(cls).items()):
        if attr.startswith("__"):
            if attr in DUNDERS and attr != "__init__":
                out.append("    " + DUNDERS[attr].format(cls=name))
            continue
        if attr.startswith("_"):
            continue
        if inspect.isdatadescriptor(member) or type(member).__name__ == "getset_descriptor":
            t = prop_type(member.__doc__)
            writable = "read and write" in (member.__doc__ or "")
            if writable:
                out.append(f"    {attr}: {t}")
            else:
                out += ["    @property", f"    def {attr}(self) -> {t}: ..."]
            continue
        if isinstance(member, staticmethod):
            f = member.__func__
            out += [
                "    @staticmethod",
                f"    def {attr}{signature(f, f.__text_signature__, f.__doc__, method=False)}: ...",
            ]
            continue
        if callable(member):
            ts = getattr(member, "__text_signature__", None)
            out.append(f"    def {attr}{signature(member, ts, member.__doc__, method=True)}: ...")
    if len(out) == 1:
        out.append("    ...")
    return out


def generate() -> str:
    m = extension()
    parts = [HEADER]
    names = sorted(n for n in dir(m) if not n.startswith("__"))
    for name in names:
        obj = getattr(m, name)
        if inspect.isclass(obj):
            parts.append("\n".join(class_stub(name, obj)) + "\n")
        elif callable(obj):
            ts = getattr(obj, "__text_signature__", None)
            parts.append(f"def {name}{signature(obj, ts, obj.__doc__, method=False)}: ...\n")
    text = "\n".join(parts)
    ast.parse(text)
    return _format(text)


def _format(text: str) -> str:
    ruff = shutil.which("ruff")
    if ruff is None:
        raise SystemExit("gen_stubs.py needs ruff (pip install --group lint)")
    out = subprocess.run(
        [
            ruff,
            "format",
            "--config",
            str(ROOT / "pyproject.toml"),
            "--stdin-filename",
            str(OUT),
            "-",
        ],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    )
    return out.stdout


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the stub is out of date")
    args = ap.parse_args()
    text = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python tools/gen_stubs.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
