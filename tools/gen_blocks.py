#!/usr/bin/env python3
"""Generate ``python/comrs/blocks.py``, the classes of the declarative blocks.

One class per entry of the registry (``comrs.spec_blocks()`` of the built extension),
named in CamelCase (``awgn_ebn0`` → ``AwgnEbn0``), with an explicit keyword-only
signature ``__init__(self, *, param: type = default, …)`` (the defaults of the
registry when they are Python literals, ``None`` otherwise, the block then choosing
its default), the documentation of the registry as docstring and its ports
(``needs``, ``gives``). Run it after changing a block, with the extension built
(``maturin develop``)::

    python tools/gen_blocks.py           # write python/comrs/blocks.py
    python tools/gen_blocks.py --check   # fail if the file is out of date (CI)

The output is formatted by ``ruff format`` (the ``lint`` dependency group).
"""

from __future__ import annotations

import argparse
import json
import keyword
import sys

from _common import ROOT, extension, ruff_format, write_or_check

OUT = ROOT / "python" / "comrs" / "blocks.py"

PY_TYPES = {
    "number": "float",
    "integer": "int",
    "boolean": "bool",
    "string": "str",
    "array": "list",
    "object": "dict",
}

HEADER = '''"""The blocks of the registry of declarative links as classes, for :class:`comrs.Chain`.

One class per entry of :func:`comrs.spec_blocks`, named in CamelCase (``awgn_ebn0`` →
:class:`AwgnEbn0`), with the parameters of the block as keyword arguments and its
documentation as docstring. A parameter given as ``comrs.var("name")`` takes the value
of the grid variable ``name``; a parameter left out takes the default of the block (the
specification lists the parameters given only). ``needs`` and ``gives`` are the facts
of the frame a block reads and adds (see :func:`comrs.spec_check_link`).

This file is generated by ``tools/gen_blocks.py`` from the registry of the extension:
do not edit it (``python tools/gen_blocks.py`` regenerates it, ``--check`` verifies it);
at import, a warning names the blocks that differ from the extension.

Example:
    >>> from comrs import blocks as B
    >>> B.AwgnEbn0(ebn0_db=10).spec()
    {'type': 'awgn_ebn0', 'ebn0_db': 10}
    >>> B.AwgnEbn0.needs, B.AwgnEbn0.gives
    (('samples', 'constellation'), ('noise',))
"""

from __future__ import annotations

from typing import Any

from comrs.block import Native, Var, _check_registry, _native_init

'''


def _registry() -> dict:
    return extension().spec_blocks()


def _yaml(text: str):
    try:
        return json.loads(extension()._yaml_to_json(text))
    except (ValueError, json.JSONDecodeError):
        return None


def _kinds(schema: dict) -> list[str]:
    """The JSON types a schema accepts."""
    if not schema:
        return []
    out: list[str] = []
    t = schema.get("type")
    if isinstance(t, str):
        out.append(t)
    elif isinstance(t, list):
        out.extend(t)
    for key in ("oneOf", "anyOf"):
        for alt in schema.get(key, []):
            sub = _kinds(alt)
            if not sub:
                return []
            out.extend(sub)
    return list(dict.fromkeys(out))


def _py_type(schema: dict) -> str:
    kinds = _kinds(schema)
    if not kinds:
        return "Any"
    types = list(dict.fromkeys(PY_TYPES.get(k, "Any") for k in kinds))
    if "float" in types and "int" in types:
        types.remove("int")
    return "Any" if "Any" in types else " | ".join(types)


def _default(info: dict) -> tuple[bool, str]:
    """Whether the parameter is required, and the Python default (source text)."""
    if info.get("required"):
        return True, ""
    kinds = _kinds(info.get("type", {}))
    v = _yaml(info["default"])
    if isinstance(v, bool):
        ok = not kinds or "boolean" in kinds
    elif isinstance(v, int | float):
        ok = not kinds or "number" in kinds or ("integer" in kinds and isinstance(v, int))
        if ok and kinds == ["number"]:
            v = float(v)
    elif isinstance(v, str):
        ok = (not kinds or "string" in kinds) and v != "none"
    else:  # lists, mappings, null: the block chooses
        ok = False
    return False, repr(v) if ok else "None"


def _class_name(kind: str) -> str:
    return "".join(p.capitalize() for p in kind.split("_"))


def _keys(schema: dict) -> list[str]:
    """The keys of a parameter that is a mapping of parameters (its ``properties``)."""
    if "properties" in schema:
        return list(schema["properties"])
    # a name or a mapping; the codes (oneOf, by their type) are documented apart
    for alt in schema.get("anyOf", []):
        if keys := _keys(alt):
            return keys
    return []


def _param_doc(name: str, info: dict) -> list[str]:
    """The Args line of a parameter (Google style)."""
    doc = info["doc"]
    if info.get("unit"):
        doc += f" [{info['unit']}]"
    if info.get("choices"):
        doc += f"; one of {', '.join(info['choices'])}"
    if keys := _keys(info.get("type", {})):
        doc += f"; keys {', '.join(keys)}"
    doc += "; required" if info.get("required") else f"; default {info['default']}"
    return [f"        {name} ({_py_type(info.get('type', {}))}): {doc}"]


def generate() -> str:
    registry = _registry()
    parts = [HEADER]
    names = []
    for kind, info in registry.items():
        cls = _class_name(kind)
        names.append(cls)
        params = info.get("params", {})
        for p in params:
            if keyword.iskeyword(p) or not p.isidentifier():
                raise SystemExit(f"block {kind}: the parameter {p!r} is not a Python name")
        needs, gives = info.get("needs", []), info.get("gives", [])
        doc = [info.get("summary", "").strip() or kind, ""]
        doc.append(
            f"Needs: {', '.join(needs) or 'nothing'}. Gives: {', '.join(gives) or 'nothing'}."
        )
        doc.append("")
        doc.append("Args:")
        for p, v in params.items():
            doc.extend(line[4:] for line in _param_doc(p, v))
        if not params:
            doc.append("    (no parameter)")
        sig, call = [], []
        for p, v in params.items():
            required, default = _default(v)
            t = _py_type(v.get("type", {}))
            t = f"{t} | Var" if t != "Any" else t
            if required:
                sig.append(f"{p}: {t}")
            else:
                sig.append(
                    f"{p}: {t}{' | None' if default == 'None' and t != 'Any' else ''} = {default}"
                )
            call.append(f"{p}={p}")
        docstring = "\n    ".join(doc).replace("\\", "\\\\")
        body = [
            f"class {cls}(Native):",
            f'    """{docstring}\n    """',
            "",
            f"    needs = {tuple(needs)!r}",
            f"    gives = {tuple(gives)!r}",
            f"    param_names = {tuple(params)!r}",
            "",
            f"    def __init__(self{', *, ' + ', '.join(sig) if sig else ''}) -> None:",
            f'        _init(self, "{kind}"{", " + ", ".join(call) if call else ""})',
            "",
            "",
        ]
        parts.append("\n".join(body))
    parts.append("_init = _native_init\n")
    parts.append(f"__all__ = {sorted(names)!r}\n")
    parts.append("_check_registry(globals())\n")
    text = "\n".join(parts)
    if ": Any" not in text.split("from comrs.block import", 1)[1]:
        # every parameter has a declared type
        text = text.replace("from typing import Any\n\n", "", 1)
    return ruff_format(text, OUT, "gen_blocks.py")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args()
    text = generate()
    return write_or_check(
        OUT,
        text,
        args.check,
        fix="python tools/gen_blocks.py",
        written=f"wrote {{path}} ({text.count('class ')} blocks)",
        up_to_date=True,
        stream=sys.stdout,
    )


if __name__ == "__main__":
    sys.exit(main())
