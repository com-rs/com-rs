#!/usr/bin/env python3
"""Render `docs/python/benchmarks.rst` from the results of the library benchmarks.

The results are the files `benchmarks/libraries/results/<scenario>.json` written by
`benchmarks/libraries/run_all.py` (see `benchmarks/libraries/README.md`): per scenario,
the error rates of every library with their confidence intervals, the closed form when
there is one, the timings on one thread and on every core, the machine, the versions,
the commit and the commands. The page shows, per scenario, what every library supports,
how its results agree with the theory or with com-rs, and how long it takes.

    python3 tools/benchmarks_page.py            # write the page
    python3 tools/benchmarks_page.py --check    # fail if the page is out of date
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "benchmarks" / "libraries" / "results"
PAGE = ROOT / "docs" / "python" / "benchmarks.rst"
REPO = "https://github.com/com-rs/com-rs/blob/main"
SCENARIOS = ["s1_awgn", "s2_rayleigh", "s3_mimo", "s4_coding", "s5_ssfm"]
ORDER = ["comrs", "comrs-spec", "comrs-rust", "komm", "opticommpy", "opticommpy-nojit", "sionna"]
NAMES = {
    "comrs": "comrs (functions)",
    "comrs-spec": "comrs.run_spec",
    "comrs-rust": "comrs binary (Rust)",
    "komm": "komm",
    "opticommpy": "OptiCommPy (numba)",
    "opticommpy-nojit": "OptiCommPy (no numba)",
    "sionna": "Sionna",
}
VERSION_OF = {
    "comrs": "comrs",
    "comrs-spec": "comrs",
    "comrs-rust": "comrs",
    "komm": "komm",
    "opticommpy": "OptiCommPy",
    "opticommpy-nojit": "OptiCommPy",
    "sionna": "sionna",
}
CASE_NAMES = {
    "qpsk": "QPSK",
    "16qam": "16-QAM",
    "bpsk": "BPSK",
    "zf": "zero forcing",
    "mmse": "MMSE",
    "ml": "ML (exhaustive)",
    "sphere": "ML (sphere decoder)",
    "conv": "convolutional (133, 171), soft Viterbi",
    "nr_ldpc": "5G NR LDPC (1024, 2048)",
    "ldpc_same_llr": "LDPC (1024, 512), same LLRs",
    "ssfm": "split-step Fourier",
}
# the unit of the times of every kind of workload: (label, factor from seconds per unit)
UNITS = {
    "bit": ("ns per bit", 1e9),
    "vector": ("µs per vector", 1e6),
    "frame": ("ms per frame", 1e3),
    "propagation": ("s per propagation", 1.0),
}
Z_MAX = 4.0

INTRO = """\
Benchmarks against other libraries
==================================

The same links simulated with com-rs and with the Python libraries that offer them —
`komm <https://github.com/rwnobrega/komm>`_, `OptiCommPy
<https://github.com/edsonportosilva/OptiCommPy>`_ (with and without numba) and `Sionna
<https://github.com/NVlabs/sionna>`_ — with the same parameters and the same number of
samples: do the results agree (with the closed form when there is one, with each other
otherwise), and how long does each library take? The :doc:`comparisons <comparisons>`
page compares the outputs of single blocks value by value; this one runs whole links.

A feature a library does not offer is marked *not available*, with the reason: no
substitute is written for it. The scripts import every library as a user would (the
GPL-3.0 code of OptiCommPy is imported by the benchmark scripts only, never copied).

.. generated by tools/benchmarks_page.py from benchmarks/libraries/results/*.json: do not edit
"""

RULES = """\
Rules
-----

- **Same work.** Same parameters, same number of bits, vectors, frames or samples
  for every library; every library draws its own bits and noise with its own
  generator and independent seeds, from the same distributions, so the results agree
  statistically, not bit for bit (the input field of the split-step case and the LLRs
  of the case "same LLRs" are identical in every library).
- **Confidence intervals.** 95 % intervals: Wilson's for independent errors; for coded
  frames and MIMO vectors, whose errors come in bursts, the interval of the mean of
  the per-frame (per-vector) error counts. A result *agrees* when every point lies
  within four standard errors of the closed form (or of com-rs, when there is no
  closed form; points without errors on both sides are skipped).
- **Timing.** ``time.perf_counter``; one warm-up run first, reported apart as *first
  call* (it contains the numba compilation, from an empty cache, and the lazy
  initialisations of PyTorch); then the median of five timed runs. The times are per
  unit of work (bit, vector, frame, propagation).
- **Threads.** Every library runs in its own process. *1 thread*: ``OMP_NUM_THREADS``,
  ``OPENBLAS_NUM_THREADS``, ``MKL_NUM_THREADS``, ``VECLIB_MAXIMUM_THREADS``,
  ``NUMBA_NUM_THREADS`` and ``RAYON_NUM_THREADS`` set to 1, ``torch.set_num_threads(1)``,
  ``threads=1`` for ``comrs.run_spec`` and ``--threads 1`` for the binary. *All
  threads*: the defaults of every library (every core; ``threads=0`` for com-rs). The
  functions of comrs are single-threaded; its Monte Carlo runner (``run_spec``, the
  binary) runs the trials in parallel.
- **Precision.** What every library computes in is stated next to its times: comrs in
  float64 (float32 on request for the split-step), komm in float64, Sionna in float32
  by default, OptiCommPy in float64 except its Gray constellations (complex64) and its
  LDPC decoder (float32 by default).
- **Sionna** 2.x is built on PyTorch (not TensorFlow); it runs on the CPU, eagerly,
  under ``torch.inference_mode()``. ``torch.compile`` is not used.
- **OptiCommPy without numba** means ``NUMBA_DISABLE_JIT=1``: numba's own switch, which
  runs every ``@njit`` function of OptiCommPy as plain Python (OptiCommPy has no option
  of its own). Its results are those of the compiled code; it is timed only.
"""


def load() -> dict[str, dict]:
    out = {}
    for s in SCENARIOS:
        path = RESULTS / f"{s}.json"
        if path.exists():
            out[s] = json.loads(path.read_text())
    return out


def table(
    header: list[str] | None, rows: list[list[str]], widths: list[int] | None = None
) -> list[str]:
    out = [".. list-table::", f"   :header-rows: {0 if header is None else 1}"]
    if widths:
        out.append("   :widths: " + " ".join(map(str, widths)))
    out.append("")
    for row in ([] if header is None else [header]) + rows:
        for i, cell in enumerate(row):
            out.append(("   * - " if i == 0 else "     - ") + (cell if cell != "" else "\\-"))
    out.append("")
    return out


def heading(text: str, ch: str) -> list[str]:
    return [text, ch * len(text), ""]


def rubric(text: str) -> list[str]:
    """A heading without a target (the cases repeat from one scenario to the next)."""
    return [f".. rubric:: {text}", ""]


def indent(lines: list[str], n: int = 3) -> list[str]:
    return [(" " * n + x) if x else "" for x in lines]


def sci(x: float | None) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "—"
    if x == 0:
        return "0"
    e = math.floor(math.log10(abs(x)))
    m = x / 10**e
    if abs(m) >= 9.995:
        m, e = m / 10, e + 1
    return f"{m:.2f}e{e}"


def num(x: float | None) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "—"
    if x >= 100:
        return f"{x:.0f}"
    if x >= 10:
        return f"{x:.1f}"
    if x >= 1:
        return f"{x:.2f}"
    return f"{x:.3g}"


def runs_by(data: dict) -> dict[tuple[str, str], dict]:
    return {(r["library"], r["threads"]): r for r in data["runs"]}


def case_results(run: dict | None, case: str) -> list[dict]:
    if not run or "cases" not in run:
        return []
    return [c for c in run["cases"] if c["case"] == case]


def se_of(p: dict) -> float:
    if "se" in p:
        return p["se"]
    return (p["hi"] - p["lo"]) / (2 * 1.96)


def agreement(points: list[dict], base: list[dict] | None) -> tuple[str, float | None]:
    """Max |z| against the theory, else against com-rs (``base``)."""
    zs = [abs(p["z"]) for p in points if p.get("z") is not None and not math.isnan(p["z"])]
    if zs:
        return "theory", max(zs)
    if base is None:
        return "", None
    zs = []
    for i in range(min(len(points), len(base))):
        p, q = points[i], base[i]
        if p["errors"] == 0 and q["errors"] == 0:
            continue
        s = math.hypot(se_of(p), se_of(q))
        if s > 0:
            zs.append(abs(p["value"] - q["value"]) / s)
    return ("comrs", max(zs)) if zs else ("comrs", None)


def support_table(data: dict, libs: list[str]) -> list[str]:
    rows = []
    for case, sup in data["support"].items():
        row = [CASE_NAMES.get(case, case)]
        for lib in libs:
            s = sup.get(lib)
            row.append("yes" if s is True else (f"not available: {s}" if s else "not run"))
        rows.append(row)
    return table(["Case", *[NAMES[x] for x in libs]], rows)


def present_libs(data: dict) -> list[str]:
    have = {r["library"] for r in data["runs"]} | {
        lib for sup in data["support"].values() for lib, s in sup.items() if s is not True
    }
    return [x for x in ORDER if x in have]


def failures(data: dict) -> list[str]:
    out = []
    for r in data["runs"]:
        if "error" in r:
            msg = r["error"].strip().splitlines()[-1] if r["error"].strip() else "failed"
            out.append(f"- {NAMES[r['library']]}, {r['threads']} thread(s): failed (``{msg}``).")
    return [*out, ""] if out else []


def error_rate_section(data: dict, libs: list[str], metric: str = "ber") -> list[str]:
    runs = runs_by(data)
    out = []
    for case in data["support"]:
        entries = []
        for lib in libs:
            for c in case_results(runs.get((lib, "1")), case):
                if "points" in c:
                    entries.append((lib, c))
        if not entries:
            continue
        base = next((c["points"] for lib, c in entries if lib == "comrs"), None)
        out += rubric(f"{CASE_NAMES.get(case, case)}: error rates")
        # agreement summary
        rows = []
        for lib, c in entries:
            pts = c["points"] if metric == "ber" else [p["bler"] for p in c["points"]]
            b = base if metric == "ber" else ([p["bler"] for p in base] if base else None)
            ref, z = agreement(pts, None if lib == "comrs" else b)
            coded = "bler" in c["points"][0]
            zb = None
            if coded and lib != "comrs" and base:
                _, zb = agreement([p["bler"] for p in c["points"]], [p["bler"] for p in base])
            worst = max((x for x in (z, zb) if x is not None), default=None)
            verdict = "—" if worst is None else ("yes" if worst <= Z_MAX else "no")
            row = [NAMES[lib], c.get("precision", ""), ref or "—", num(z) if z is not None else "—"]
            if coded:
                row.append(num(zb) if zb is not None else "—")
            rows.append([*row, verdict, pts[0].get("ci", "")])
        coded = "bler" in entries[0][1]["points"][0]
        cols = ["Library", "Precision", "Against", "max abs(z), BER"] + (
            ["max abs(z), FER"] if coded else []
        )
        out += table([*cols, "Agrees", "BER interval"], rows)
        # the values
        xs = [p["ebn0_db"] for p in entries[0][1]["points"]]
        theo = [p.get("theory", p.get("union_bound")) for p in entries[0][1]["points"]]
        has_theory = any(t is not None for t in theo)
        header = ["Eb/N0 (dB)"]
        if has_theory:
            header.append("union bound" if case == "conv" else "theory")
        header += [NAMES[lib] for lib, _ in entries]
        rows = []
        for i, x in enumerate(xs):
            row = [f"{x:g}"]
            if has_theory:
                row.append(sci(theo[i]))
            for _, c in entries:
                p = c["points"][i]
                row.append(f"{sci(p['value'])} [{sci(p['lo'])}, {sci(p['hi'])}]")
            rows.append(row)
        n_bits = entries[0][1]["points"][0]["total"]
        out += [
            f".. dropdown:: BER and its 95 % interval, every point ({n_bits:,} bits per point)",
            "",
        ]
        out += indent(table(header, rows))
        if any("bler" in p for p in entries[0][1]["points"]):
            rows = []
            for i, x in enumerate(xs):
                row = [f"{x:g}"]
                for _, c in entries:
                    q = c["points"][i]["bler"]
                    row.append(f"{sci(q['value'])} [{sci(q['lo'])}, {sci(q['hi'])}]")
                rows.append(row)
            n_frames = entries[0][1]["points"][0]["bler"]["total"]
            out += [
                f".. dropdown:: Frame error rate and its 95 % interval ({n_frames:,} frames per point)",
                "",
            ]
            out += indent(table(["Eb/N0 (dB)", *[NAMES[lib] for lib, _ in entries]], rows))
    return out


def timing_section(
    data: dict, libs: list[str], key: str = "timing", title: str = "time"
) -> list[str]:
    runs = runs_by(data)
    out = []
    for case in data["support"]:
        variants: dict[tuple[str, str], dict[str, dict]] = {}
        for lib in libs:
            for t in data["thread_modes"]:
                for c in case_results(runs.get((lib, t)), case):
                    if key in c:
                        variants.setdefault((lib, c.get("variant", "")), {})[t] = c
        if not variants:
            continue
        any_c = next(iter(next(iter(variants.values())).values()))
        unit_label, factor = UNITS[any_c[key]["unit"]]
        base = variants.get(("comrs", "f64" if case == "ssfm" else ""), {}).get("1")
        base_t = base[key]["median_s"] / base[key]["units"] if base else None
        rows = []
        for (lib, variant), by_t in variants.items():
            c1 = by_t.get("1") or next(iter(by_t.values()))
            name = NAMES[lib] + (f", {variant}" if variant else "")
            row = [name, c1.get("precision", "")]
            for t in data["thread_modes"]:
                c = by_t.get(t)
                row.append(num(c[key]["median_s"] / c[key]["units"] * factor) if c else "—")
            t1 = by_t.get("1")
            rel = (t1[key]["median_s"] / t1[key]["units"]) / base_t if (t1 and base_t) else None
            row.append(num(rel) if rel is not None else "—")
            first = c1.get("first_call_s", c1[key].get("warmup_s"))
            row.append(f"{first:.3g} s" if first is not None else "—")
            rows.append(row)
        workload = any_c[key]["workload"]
        modes = [("1 thread" if t == "1" else "all threads") for t in data["thread_modes"]]
        out += rubric(f"{CASE_NAMES.get(case, case)}: {title}")
        out += [
            f"Median of {any_c[key]['repeats']} runs, {unit_label}; workload: {workload}. "
            "*Relative*: the 1-thread time over that of comrs (functions) on 1 thread.",
            "",
        ]
        out += table(["Library", "Precision", *modes, "Relative", "First call"], rows)
    return out


def scenario_section(name: str, data: dict) -> list[str]:
    libs = present_libs(data)
    out = heading(data["title"], "-")
    out += [data["description"], ""]
    out += ["Parameters:", ""]
    for k, v in data["parameters"].items():
        key = {"ebn0_db": "Eb/N0 (dB)", **CASE_NAMES}.get(k, k.replace("_", " "))
        out.append(f"- {key}: {v if not isinstance(v, list) else ', '.join(f'{x:g}' for x in v)}")
    out += ["", f"Script: `{data['script']} <{REPO}/{data['script']}>`_.", ""]
    out += [
        ".. dropdown:: The script",
        "",
        f"   .. literalinclude:: ../../{data['script']}",
        "      :language: python",
        "",
    ]
    out += rubric("Support")
    out += support_table(data, libs)
    out += failures(data)
    if name == "s5_ssfm":
        out += ssfm_section(data)
    else:
        out += error_rate_section(data, libs)
    if name == "s4_coding":
        out += same_llr_section(data)
        out += timing_section(data, libs, "timing", "decoder time")
        out += timing_section(data, libs, "timing_chain", "whole-chain time")
    else:
        out += timing_section(data, libs)
    out += [".. dropdown:: The commands of every run", "", "   .. code-block:: bash", ""]
    for r in data["runs"]:
        if "command" in r:
            out.append(f"      {r['command']}")
    out.append("")
    return out


def same_llr_section(data: dict) -> list[str]:
    totals: dict[str, list[int]] = {}
    for r in data.get("agreement", {}).get("same_llr_vs_comrs", []):
        t = totals.setdefault(r["library"], [0, 0, 0, 0])
        t[0] += 1
        t[1] += r["frames"]
        t[2] += r["same_bit_errors"]
        t[3] += r["same_frame_outcome"]
    if not totals:
        return []
    rows = [
        [
            NAMES[lib],
            f"{t[0]}",
            f"{t[1]}",
            f"{t[2]} ({100 * t[2] / t[1]:.2f} %)",
            f"{t[3]} ({100 * t[3] / t[1]:.2f} %)",
        ]
        for lib, t in totals.items()
    ]
    out = rubric("Same LLRs: the decisions frame by frame")
    out += [
        "The decoders received identical LLRs. Over all the points: the frames where a library "
        "makes as many bit errors as comrs, and the frames it decodes (or fails to decode) as "
        "comrs does.",
        "",
    ]
    return out + table(
        ["Library", "Points", "Frames", "Same bit errors", "Same frame outcome"], rows
    )


def ssfm_section(data: dict) -> list[str]:
    ag = data.get("agreement", {})
    rows = []
    names = {
        "comrs_f64": "comrs, float64",
        "comrs_f32": "comrs, float32",
        "opticommpy_f64": "OptiCommPy, float64",
        "sionna_single": "Sionna, float32",
        "sionna_double": "Sionna, float64",
        "sionna_single_plain": "Sionna, float32, its own convention (not conjugated)",
        "sionna_double_plain": "Sionna, float64, its own convention (not conjugated)",
    }
    for r in ag.get("nmse", []):
        rows.append(
            [
                names.get(r["field"], r["field"]),
                sci(r["nmse_vs_comrs_f64"]),
                sci(r["nmse_vs_reference"]),
            ]
        )
    if not rows:
        return []
    out = rubric("Output fields")
    out += [
        f"NMSE of the output field, ``sum |a - b|^2 / sum |b|^2``, against comrs in float64 "
        f"at the same step and against the step-converged reference (comrs, "
        f"{ag.get('reference_step_km', 0.05):g} km). The NMSE against the reference is the "
        "error of the 1 km step itself.",
        "",
    ]
    return out + table(["Field", "NMSE vs comrs (float64, 1 km)", "NMSE vs reference"], rows)


def machine_section(data: dict) -> list[str]:
    m, g, v = data["machine"], data["git"], data["versions"]
    cores = f"{m['logical_cores']} logical"
    if m.get("core_levels"):
        cores += " (" + ", ".join(lv.lower() for lv in m["core_levels"]) + ")"
    out = heading("Machine and versions", "-")
    rows = [
        ["CPU", m.get("cpu") or "—"],
        ["Cores", cores],
        ["Memory", f"{m.get('ram_gb')} GB"],
        ["System", f"macOS {m['macos']}" if m.get("macos") else m.get("platform", "—")],
        ["Python", m.get("python", "—")],
        ["Rust", m.get("rustc") or "—"],
        [
            "com-rs commit",
            f"``{(g.get('commit') or '?')[:12]}``"
            + (" (with uncommitted changes)" if g.get("dirty") else ""),
        ],
        ["Generated", data["generated_utc"]],
    ]
    for pkg in ["comrs", "komm", "OptiCommPy", "sionna", "torch", "numba", "numpy", "scipy"]:
        rows.append([pkg, v.get(pkg) or "not installed"])
    return out + table(None, rows, [30, 70])


def libraries_section(data: dict) -> list[str]:
    out = heading("Libraries", "-")
    rows = []
    for lib in ORDER:
        if lib in data["libraries"]:
            rows.append(
                [NAMES[lib], data["libraries"][lib], data["versions"].get(VERSION_OF[lib]) or "—"]
            )
    return out + table(["Name on this page", "What runs", "Version"], rows, [22, 63, 15])


REPRODUCE = """\
Reproducing
-----------

On a quiet machine (the timings are wrong on a loaded one), from the root of the
repository:

.. code-block:: bash

   uv venv --python 3.12 benchmarks/libraries/.venv
   source benchmarks/libraries/.venv/bin/activate
   uv pip install -r benchmarks/libraries/requirements.txt
   maturin develop --release                    # comrs, from this checkout
   cd benchmarks/libraries
   python run_all.py                            # builds target/release/comrs first
   python ../../tools/benchmarks_page.py

``python run_all.py --quick`` runs everything at small sizes in about two minutes, to
check that it works (its timings mean nothing). The versions are pinned in
`requirements.txt <{repo}/benchmarks/libraries/requirements.txt>`_; see
`benchmarks/libraries/README.md <{repo}/benchmarks/libraries/README.md>`_.
"""


def render() -> str:
    results = load()
    lines = [INTRO]
    if not results:
        lines += ["No results yet: run ``benchmarks/libraries/run_all.py`` (see below).", ""]
        lines += [RULES, REPRODUCE.format(repo=REPO)]
        return "\n".join(lines).rstrip() + "\n"
    first = next(iter(results.values()))
    if any(d["quick"] for d in results.values()):
        lines += [
            ".. warning::",
            "",
            "   These results come from a ``--quick`` run: small sizes, wide intervals, and",
            "   timings that mean nothing. Run ``run_all.py`` without ``--quick`` on a quiet",
            "   machine.",
            "",
        ]
    lines += [RULES]
    lines += libraries_section(first)
    lines += machine_section(first)
    lines += [REPRODUCE.format(repo=REPO)]
    for name, data in results.items():
        lines += scenario_section(name, data)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = p.parse_args()
    text = render()
    if args.check:
        if not PAGE.exists() or PAGE.read_text() != text:
            print(
                f"{PAGE.relative_to(ROOT)} is out of date: run python3 tools/benchmarks_page.py",
                file=sys.stderr,
            )
            return 1
        return 0
    PAGE.write_text(text)
    print(f"wrote {PAGE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
