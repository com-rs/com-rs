"""The blocks of the registry of declarative links as classes, for :class:`comrs.Chain`.

One class per entry of :func:`comrs.spec_blocks`, named in CamelCase (``awgn_ebn0`` →
:class:`AwgnEbn0`), with the parameters of the block as keyword arguments and its
documentation as docstring. A parameter given as ``comrs.var("name")`` takes the value
of the grid variable ``name``; a parameter left out takes the default of the block (the
specification lists the parameters given only). ``needs`` and ``gives`` are the facts
of the frame a block reads and adds (see :func:`comrs.spec_check_link`).

This file is generated by ``tools/gen_blocks.py`` from the registry of the extension:
do not edit it (``python tools/gen_blocks.py`` regenerates it, ``--check`` verifies it);
at import, a warning names the blocks that differ from the extension.

Example:
    >>> from comrs import blocks as B
    >>> B.AwgnEbn0(ebn0_db=10).spec()
    {'type': 'awgn_ebn0', 'ebn0_db': 10}
    >>> B.AwgnEbn0.needs, B.AwgnEbn0.gives
    (('samples', 'constellation'), ('noise',))
"""

