    #[test]
    fn taps_have_their_powers_and_the_jakes_autocorrelation() {
        let ch = Tdl::new(&TdlParams {
            taps: vec![(0.0, 0.0), (1e-5, -3.0)],
            doppler_hz: 100.0,
            sample_rate: 1e6,
            ..TdlParams::default()
        })
        .unwrap();
        let mut rng = Rng::new(1);
        let lag = 2500; // 2π f_D m / f_s = π/2: J0 ≈ 0.472
        let n = lag + 1;
        let (mut p0, mut p1, mut r) = (0.0, 0.0, C64::new(0.0, 0.0));
        let trials = 2000;
        for _ in 0..trials {
            let t = ch.draw(n, &mut rng);
            p0 += t.coefficient(0, 0, 0, 0).norm_sqr();
            p1 += t.coefficient(1, 0, 0, 0).norm_sqr();
            r += t.coefficient(0, 0, 0, 0) * t.coefficient(0, lag, 0, 0).conj();
        }
        let tf = f64::from(trials);
        let total = 1.0 + 10f64.powf(-0.3);
        assert!((p0 / tf - 1.0 / total).abs() < 0.05);
        assert!((p1 / tf - 10f64.powf(-0.3) / total).abs() < 0.04);
        // J0(π/2) = 0.4720
        assert!(((r / tf).re / (p0 / tf) - 0.472).abs() < 0.05, "{}", (r / tf).re / (p0 / tf));
    }

    #[test]
    fn a_static_channel_is_a_convolution_and_its_frequency_response_matches() {
        let ch =
            Tdl::new(&TdlParams { taps: Profile::Epa.taps(), sample_rate: 30.72e6, ..TdlParams::default() }).unwrap();
        let mut rng = Rng::new(2);
        let x: Vec<C64> = (0..256).map(|_| rng.complex_gaussian()).collect();
        let (y, taps) = ch.fade(&Signal::from_stream(x.clone(), Hertz(30.72e6)).unwrap(), &mut rng).unwrap();
        // circular check on a cyclic block: y = x ⊛ h away from the start
        let bins: Vec<usize> = (0..256).collect();
        let h = taps.frequency_response(0, &bins, 256);
        let mut xp = x.clone();
        xp.extend_from_slice(&x);
        let mut yp = vec![C64::new(0.0, 0.0); 512];
        for (l, &d) in taps.delays().iter().enumerate() {
            for i in d..512 {
                yp[i] += taps.coefficient(l, 0, 0, 0) * xp[i - d];
            }
        }
        let spec_y = com_math::fft::fft(&yp[256..]);
        let spec_x = com_math::fft::fft(&x);
        for k in 0..256 {
            assert!((spec_y[k] - h[k] * spec_x[k]).norm() < 1e-9);
        }
        assert!((y.stream(0)[100] - yp[100]).norm() < 1e-12);
        assert!((ch.frequency_correlation(0, 256).re - 1.0).abs() < 1e-12);
    }

